## Основные методы

# *   **`get()`** — получает введённый текст. **Важное замечание:** метод всегда возвращает строку, даже если пользователь ввёл число. Если нужно использовать значение для вычислений (например, сложить с числом), придётся вручную конвертировать тип (например, `int(entry.get())`) и обработать возможную ошибку, если ввод некорректный. [1](https://it-start.online/articles/python/biblioteki-python/tkinter/vidzhet-entry-v-tkinter-vvod-dannyh-v-python)
# *   **`insert(index, text)`** — вставляет `text` в поле. Первый аргумент — позиция: `0` означает начало, `tk.END` — конец.
# *   **`delete(first, last=None)`** — удаляет символы. Если вызвать `delete(0, tk.END)`, поле полностью очистится.

## Полезные параметры

# *   **`show="*"`** — маскирует ввод (например, для пароля). При этом в поле будут отображаться только звёздочки, но метод `get()` вернёт реальные данные пользователя.
# *   **`state="disabled"`** — блокирует поле (можно установить и через свойство `state` виджета).
# *   **`textvariable=StringVar()`** — позволяет связать поле с переменной (например, чтобы при изменении переменной обновлялся и интерфейс). Это удобно для двусторонней связи.
# *   **`justify`**, **`relief`**, **`selectbackground`**, **`selectforeground`** — для стилизации (выравнивание, тип границы, цвета выделения).

